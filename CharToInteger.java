public class CharToInteger {
    public static void main(String[] args) {
        System.out.println("Character\tInteger Equivalent");
        System.out.println("--------------------------------");

        System.out.println("A\t\t" + (int)'A');
        System.out.println("B\t\t" + (int)'B');
        System.out.println("C\t\t" + (int)'C');
        System.out.println("a\t\t" + (int)'a');
        System.out.println("b\t\t" + (int)'b');
        System.out.println("c\t\t" + (int)'c');
        System.out.println("0\t\t" + (int)'0');
        System.out.println("1\t\t" + (int)'1');
        System.out.println("2\t\t" + (int)'2');
        System.out.println("$\t\t" + (int)'$');
        System.out.println("*\t\t" + (int)'*');
        System.out.println("+\t\t" + (int)'+');
        System.out.println("/\t\t" + (int)'/');
        System.out.println(" \t\t" + (int)' ');
    }
}
